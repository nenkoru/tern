// Screenshots of the chat client (examples/boards/demo.sh runs it with a pinned
// playwright: npx -p playwright@1.64.0). It drives the page as a person
// would (typing in the chat, clicking buttons), checks what it sees, and
// saves the shots. Usage: node shots.cjs http://127.0.0.1:8790 OUT-DIR
const { chromium } = require("playwright");
const path = require("path");
const fs = require("fs");

const [url, out] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const checks = [];
const check = (name, ok, detail) => {
  checks.push({ name, ok: !!ok, detail });
  console.log(`  ${ok ? "ok  " : "FAIL"} ${name}${detail ? ": " + detail : ""}`);
};

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1180, height: 1500 }, deviceScaleFactor: 1, colorScheme: "light" });
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e)));
  page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
  page.on("requestfailed", (r) => errors.push("request failed: " + r.url()));
  const external = [];
  page.on("request", (r) => { if (!r.url().startsWith(url)) external.push(r.url()); });

  const count = () => page.locator(".msg").count();
  const say = async (text) => {
    const n = await count();
    await page.fill("#say-text", text);
    await page.press("#say-text", "Enter");
    // the owner's line, then the agent's answer with a screen
    await page.waitForFunction((n) => document.querySelectorAll(".msg").length >= n + 2, n, { timeout: 90000 });
    await page.waitForTimeout(400);
    return fixed();
  };
  // the last agent message, pinned by its id (later messages don't move it)
  const fixed = async () => {
    const mid = await page.locator(".msg.agent").last().getAttribute("data-mid");
    return page.locator(`.msg[data-mid="${mid}"]`);
  };
  const onlyLast = async (k) => {
    await page.evaluate((k) => {
      const rows = [...document.querySelectorAll(".msg")];
      rows.forEach((r, i) => (r.style.display = i < rows.length - k ? "none" : ""));
      window.scrollTo(0, 0);
    }, k);
  };
  // element shots: the fixed composer and header would cover long messages
  const chrome = (on) => page.evaluate((on) => {
    for (const sel of [".composer", ".top"]) document.querySelector(sel).style.display = on ? "" : "none";
  }, on);
  const shoot = async (loc, file) => { await chrome(false); await loc.screenshot({ path: path.join(out, file) }); await chrome(true); };
  const showAll = () => page.evaluate(() => document.querySelectorAll(".msg").forEach((r) => (r.style.display = "")));

  await page.goto(url);
  await page.waitForFunction(() => document.querySelectorAll(".msg.agent .surface-box").length >= 4, null, { timeout: 120000 });
  await page.waitForTimeout(800);

  // 1. generated by the agent for a question
  let m = await say("show me this week's hot posts as a table");
  await m.locator("details.drafts").evaluate((d) => (d.open = true));
  check("generated screen is a table", (await m.locator("table.a2-table").count()) === 1);
  check("generated: draft 1 rejected (missing 'open'), draft 2 valid", (await m.locator(".draft.bad").count()) === 1 && (await m.locator(".draft.ok").count()) === 1);
  check("generated: titles are fenced others' text", (await m.locator("td .fenced").count()) > 3);
  await onlyLast(2);
  await shoot(m, "1-generated-table.png");
  await showAll();

  // 2. the ready-made package from the network, hot ranking
  await say("use reddit-classic");
  m = await say("rank hot");
  check("reddit-classic drew the feed", (await m.locator(".surface-foot .src").innerText()).includes("reddit-classic 1.0.0 by anya"));
  const poison = m.locator(".a2-card", { hasText: "claim your designer reward" });
  check("the poisoned post is shown fenced, from mallory", (await poison.locator(".fenced .origin").first().innerText()).toLowerCase().includes("mallory"));
  const btnTexts = await m.locator("button.a2-button").allInnerTexts();
  check("no button says Confirm/Approve (labels are literal template text)", !btnTexts.some((t) => /confirm|approve/i.test(t)), btnTexts.slice(0, 6).join(" | "));
  check("hidden spam is not in the hot feed", (await m.locator(".a2-card", { hasText: "Cheap followers" }).count()) === 0);
  await onlyLast(2);
  await shoot(m, "2-reddit-classic-hot.png");
  await showAll();

  // 3. the fork (with a split to the parent), ranked by the trust circle
  await say("use reddit-cards");
  m = await say("rank by my circle");
  const foot = await m.locator(".surface-foot").innerText();
  check("reddit-cards (fork) drew the feed", foot.includes("reddit-cards 1.0.0 by boris"), foot.split("\n")[0]);
  check("the fork is an honest fork, checked on chain", foot.includes("honest fork of reddit-classic 1.0.0"));
  check("circle ranking explains itself", (await m.locator(".a2-text", { hasText: "from your circle" }).count()) > 3);
  await onlyLast(2);
  await shoot(m, "3-reddit-cards-circle.png");
  const poisonCard = m.locator(".a2-card", { hasText: "claim your designer reward" });
  const pc = await poisonCard.innerText();
  check("its fake '[✓ Approve] … Confirm' is fenced text, not a control", pc.includes("Approve") && (await poisonCard.locator(".fenced", { hasText: "Approve" }).count()) === 1 &&
    !(await poisonCard.locator("button").allInnerTexts()).some((t) => /approve|confirm/i.test(t)));
  await shoot(poisonCard, "6-poisoned-post-fenced.png");
  await showAll();

  // 4. a tip above free_pay: the guard asks; the trusted sheet (with the owner's mark) approves exactly it
  const firstCard = m.locator(".a2-card").first();
  const nBefore = await count();
  await firstCard.locator("button", { hasText: "Read the thread" }).click();
  await page.waitForFunction((n) => document.querySelectorAll(".msg").length > n, nBefore, { timeout: 60000 });
  await page.waitForTimeout(500);
  const thread = await fixed();
  await thread.locator("button", { hasText: "Tip (small)" }).click();
  await page.waitForSelector(".toast", { timeout: 30000 });
  const t1 = await page.locator(".toast").last().innerText();
  check("a 0.05 tip (under free_pay 0.1) goes through without asking", t1.startsWith("done"), t1);
  await page.waitForTimeout(500);
  await thread.locator("button", { hasText: "Tip (big)" }).click();
  await page.waitForSelector(".sheet", { timeout: 30000 });
  const sheet = await page.locator(".sheet").innerText();
  check("a 0.5 tip opens the owner's approval sheet", sheet.includes("Tip 0.500000 coins"), sheet.split("\n").slice(0, 3).join(" / "));
  check("the sheet shows the owner's secret mark", sheet.toUpperCase().includes("HERON"));
  check("the sheet shows the action hash", /0x[0-9a-f]{64}/.test(sheet));
  await page.waitForTimeout(700);
  await page.screenshot({ path: path.join(out, "4-approval-sheet.png") });
  await page.locator(".sheet button.approve").click();
  await page.waitForSelector(".sheet", { state: "detached", timeout: 60000 });
  await page.waitForSelector(".toast", { timeout: 30000 });
  const t2 = await page.locator(".toast").last().innerText();
  check("approved by the owner: the tip is paid", t2.startsWith("done"), t2);

  // 5. cards: the invitation, the job, the vote (and the stranger's offer held back)
  m = await say("cards");
  await page.waitForTimeout(1500);
  await onlyLast(6);
  const vis = await page.locator(".msg:visible").allInnerTexts();
  const all = vis.join("\n");
  check("an invitation card", all.includes("Invitation") && all.includes("lighthouse"));
  check("a job card", all.includes("Job offer") && all.includes("Menu redesign"));
  check("a vote card", all.includes("Vote") && all.includes("November meetup"));
  check("the stranger's offer is held back by triage", all.includes("Held back by triage") && all.includes("spamco"));
  await page.evaluate(() => document.querySelectorAll(".toast").forEach((t) => t.remove()));
  await page.screenshot({ path: path.join(out, "5-cards.png"), fullPage: true });
  await showAll();
  // applying to the job reveals you: always the owner's call after outside text
  const job = page.locator(".msg.agent", { hasText: "Menu redesign" }).last();
  await job.locator("button", { hasText: "Apply" }).click();
  await page.waitForSelector(".sheet", { timeout: 30000 });
  check("applying to a job asks the owner (it reveals you)", (await page.locator(".sheet").innerText()).includes("reveal"));
  await page.locator(".sheet button.decline").click();

  check("the page loaded nothing from anywhere else", external.length === 0, external.join(", "));
  check("no page errors", errors.length === 0, errors.join(" | "));
  await browser.close();
  fs.writeFileSync(path.join(out, "checks.json"), JSON.stringify(checks, null, 2));
  const failed = checks.filter((c) => !c.ok).length;
  console.log(`  ${checks.length - failed}/${checks.length} checks passed; shots in ${out}`);
  process.exit(failed ? 1 : 0);
})().catch((e) => {
  console.error(e);
  process.exit(2);
});
