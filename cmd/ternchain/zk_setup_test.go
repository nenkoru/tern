// TestZKSetup makes the circuits' keys (internal/zk/keys/*.ccs|pk|vk), their Solidity
// verifiers and contracts/Poseidon2.sol. A local, single-party Groth16 setup:
// whoever ran it could forge proofs. Devnet only, NOT for production
// (docs/PRIVACY.md): the verifiers carry CEREMONY = 0 and refuse to deploy off the
// devnet chain ids (zk.DevnetChainIDs); a launch runs ternchain ceremony
// (ceremony.go). Then: node contracts/build.js && go build ./....
//
//	TERN_ZK_SETUP=1 go test -run TestZKSetup ./cmd/ternchain          (keys, verifiers and Poseidon2.sol)
//	TERN_ZK_SETUP=poseidon go test -run TestZKSetup ./cmd/ternchain   (Poseidon2.sol only)
//	TERN_ZK_SETUP=verifiers go test -run TestZKSetup ./cmd/ternchain  (the verifiers from the embedded keys only)
func TestZKSetup(t *testing.T) {
	if os.Getenv("TERN_ZK_SETUP") == "" {
		t.Skip("TERN_ZK_SETUP=1 makes new keys (and invalidates proofs for deployed verifiers)")
	}
	hasher, lib := poseidonSol()
	must(t, os.WriteFile(repo("contracts/Poseidon2Hasher.sol"), []byte(hasher), 0o644))
	must(t, os.WriteFile(repo("contracts/Poseidon2.sol"), []byte(lib), 0o644))
	if os.Getenv("TERN_ZK_SETUP") == "poseidon" { // the hash contract only; keys stay
		return
	}
	if os.Getenv("TERN_ZK_SETUP") == "verifiers" { // the verifiers again, from the keys there are
		for _, c := range [][2]string{{"withdraw", "PoolVerifier"}, {"vote", "VoteVerifier"}} {
			vk, err := zk.EmbeddedVK(c[0])
			must(t, err)
			src, err := zk.VerifierSolidity(vk, c[0], c[1], [32]byte{})
			must(t, err)
			must(t, os.WriteFile(repo("contracts/"+c[1]+".sol"), []byte(src), 0o644))
		}
		return
	}
	for _, c := range []struct {
		name, contract string
		circuit        frontend.Circuit
	}{{"withdraw", "PoolVerifier", &zk.WithdrawCircuit{}}, {"vote", "VoteVerifier", &zk.VoteCircuit{}}} {
		ccs, err := frontend.Compile(ecc.BN254.ScalarField(), r1cs.NewBuilder, c.circuit)
		if err != nil {
			t.Fatal(err)
		}
		pk, vk, err := groth16.Setup(ccs)
		if err != nil {
			t.Fatal(err)
		}
		var b bytes.Buffer
		ccs.WriteTo(&b)
		must(t, os.WriteFile(repo("internal/zk/keys/"+c.name+".ccs"), b.Bytes(), 0o644))
		b.Reset()
		pk.WriteRawTo(&b)
		must(t, os.WriteFile(repo("internal/zk/keys/"+c.name+".pk"), b.Bytes(), 0o644))
		b.Reset()
		vk.WriteTo(&b)
		must(t, os.WriteFile(repo("internal/zk/keys/"+c.name+".vk"), b.Bytes(), 0o644))
		src, err := zk.VerifierSolidity(vk, c.name, c.contract, [32]byte{}) // CEREMONY 0: the devnet keys
		must(t, err)
		must(t, os.WriteFile(repo("contracts/"+c.contract+".sol"), []byte(src), 0o644))
		t.Logf("%s: %d constraints, %d public inputs", c.name, ccs.GetNbConstraints(), ccs.GetNbPublicVariables()-1)
	}
}

func must(t *testing.T, err error) {
	t.Helper()
	if err != nil {
		t.Fatal(err)
	}
}

// poseidonSol: Poseidon2 compression in Yul, unrolled, with gnark-crypto's
// round keys, and the empty-subtree roots of the Merkle trees.
func poseidonSol() (hasher, lib string) {
	params := p2.GetDefaultParameters()
	rk := params.RoundKeys
	rf := params.NbFullRounds / 2
	var s strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&s, f, a...) }
	w(`// SPDX-License-Identifier: Apache-2.0
// Generated by zk_setup_test.go from gnark-crypto: do not edit.
pragma solidity ^0.8.24;

/// Poseidon2 over BN254 (t=2, rF=6, rP=50, x^5), gnark-crypto's parameters,
/// and its 2-to-1 compression: compress(l, r) = perm(l, r)[1] + r. A contract
/// of its own (64 bytes in, 32 out), so callers stay small: one copy of the
/// unrolled rounds on chain, a warm call costs about 200 gas more.
contract Poseidon2Hasher {
    fallback() external {
        assembly {
            if iszero(eq(calldatasize(), 64)) { revert(0, 0) }
            // calldataload(64) is 0 here; it keeps p on the stack (the optimizer
            // would otherwise reload the 32-byte constant from code every use)
            let p := xor(calldataload(64), %s)
            let l := calldataload(0)
            let r := calldataload(32)
            if or(iszero(lt(l, p)), iszero(lt(r, p))) { revert(0, 0) }
            let a := l
            let b := r
            // Lazy reduction: values stay below 4p < 2^256 between mulmods.
            let x := 0
            let t := add(a, b)
            a := add(t, a)
            b := add(t, b)
`, zk.Modulus.String())
	sbox := func(v string) {
		w("            x := mulmod(%s, %s, p)\n            x := mulmod(x, x, p)\n            %s := mulmod(x, %s, p)\n", v, v, v, v)
	}
	full := func(i int) {
		w("            a := add(a, %s)\n", rk[i][0].String())
		sbox("a")
		w("            b := add(b, %s)\n", rk[i][1].String())
		sbox("b")
		w("            t := add(a, b)\n            a := add(t, a)\n            b := add(t, b)\n")
	}
	for i := 0; i < rf; i++ {
		full(i)
	}
	w("            b := mod(b, p)\n")
	for i := rf; i < rf+params.NbPartialRounds; i++ {
		w("            a := add(a, %s)\n", rk[i][0].String())
		sbox("a")
		w("            t := add(a, b)\n            a := add(a, t)\n            b := addmod(add(b, b), t, p)\n")
	}
	for i := rf + params.NbPartialRounds; i < params.NbFullRounds+params.NbPartialRounds; i++ {
		full(i)
	}
	w(`            mstore(0, addmod(b, r, p))
            return(0, 32)
        }
    }
}
`)
	hasher = s.String()
	s.Reset()
	w(`// SPDX-License-Identifier: Apache-2.0
// Generated by zk_setup_test.go from gnark-crypto: do not edit.
pragma solidity ^0.8.24;

/// Hashes over the hasher: H(x1..xn) = compress(..compress(n, x1).., xn);
/// trees: node = compress(left, right), empty leaf 0. The circuits (internal/zk)
/// hash the same.
library Poseidon2 {
    uint256 internal constant P = %s;

    function compress(address h, uint256 l, uint256 r) internal view returns (uint256 o) {
        assembly {
            let m := mload(0x40)
            mstore(m, l)
            mstore(add(m, 32), r)
            if iszero(staticcall(gas(), h, m, 64, m, 32)) { revert(0, 0) }
            o := mload(m)
        }
    }

    function hash1(address h, uint256 x) internal view returns (uint256) {
        return compress(h, 1, x);
    }

    function hash2(address h, uint256 x, uint256 y) internal view returns (uint256) {
        return compress(h, compress(h, 2, x), y);
    }

    function hash3(address h, uint256 x, uint256 y, uint256 z) internal view returns (uint256) {
        return compress(h, compress(h, compress(h, 3, x), y), z);
    }

    /// The root of an empty subtree of height i (i <= 20).
    function zero(uint256 i) internal pure returns (uint256) {
`, zk.Modulus.String())
	for i := 0; i <= 20; i++ {
		w("        if (i == %d) return %s;\n", i, zk.ZeroAt(i).String())
	}
	w(`        revert("depth");
    }
}
`)
	return hasher, s.String()
}
